function slug(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

function applyTranslations() {
  document.documentElement.lang = currentLang;
  document.documentElement.dir = "ltr";
  document.body.classList.toggle("lang-ar", currentLang === "ar");
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (i18n[currentLang][key]) node.textContent = i18n[currentLang][key];
  });
  languageToggle.textContent = currentLang === "ar" ? "EN" : "AR";
  renderProjects();
  renderWebsites();
  renderCaseStudies();
  if (window.lucide) window.lucide.createIcons();
  startWebsiteSlider();
}

function startWebsiteSlider() {
  stopWebsiteSlider();
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  websiteSliderTimer = window.setInterval(() => {
    if (websiteRail.matches(":hover, :focus-within")) return;
    const firstCard = websiteRail.querySelector(".website-card");
    if (!firstCard) return;
    const step = firstCard.getBoundingClientRect().width + 16;
    const maxScroll = websiteRail.scrollWidth - websiteRail.clientWidth;
    const next = websiteRail.scrollLeft + step >= maxScroll - 8 ? 0 : websiteRail.scrollLeft + step;
    websiteRail.scrollTo({ left: next, behavior: "smooth" });
  }, 3600);
}

function stopWebsiteSlider() {
  if (websiteSliderTimer) window.clearInterval(websiteSliderTimer);
}

function setupGalleryDialog() {
  document.addEventListener("click", (event) => {
    const trigger = event.target.closest("[data-open-image]");
    if (!trigger) return;
    dialogImage.src = trigger.dataset.openImage;
    dialogImage.alt = trigger.dataset.caption;
    dialogCaption.textContent = trigger.dataset.caption;
    dialog.showModal();
  });

  closeDialog.addEventListener("click", () => dialog.close());
  dialog.addEventListener("click", (event) => {
    if (event.target === dialog) dialog.close();
  });
}

function setupNavigation() {
  navToggle.addEventListener("click", () => {
    const isOpen = navLinks.classList.toggle("open");
    document.body.classList.toggle("menu-open", isOpen);
    navToggle.setAttribute("aria-expanded", String(isOpen));
  });

  navLinks.addEventListener("click", (event) => {
    if (event.target.closest("a")) {
      navLinks.classList.remove("open");
      document.body.classList.remove("menu-open");
      navToggle.setAttribute("aria-expanded", "false");
    }
  });
}

function setupTheme() {
  const savedTheme = localStorage.getItem("portfolio-theme");
  if (savedTheme) document.documentElement.dataset.theme = savedTheme;

  themeToggle.addEventListener("click", () => {
    const nextTheme = document.documentElement.dataset.theme === "light" ? "dark" : "light";
    document.documentElement.dataset.theme = nextTheme;
    localStorage.setItem("portfolio-theme", nextTheme);
  });
}

function setupLanguage() {
  languageToggle.addEventListener("click", () => {
    currentLang = currentLang === "ar" ? "en" : "ar";
    localStorage.setItem("portfolio-lang", currentLang);
    applyTranslations();
  });
}

function setupWebsiteSliderControls() {
  websiteRail.addEventListener("mouseenter", stopWebsiteSlider);
  websiteRail.addEventListener("mouseleave", startWebsiteSlider);
  websiteRail.addEventListener("focusin", stopWebsiteSlider);
  websiteRail.addEventListener("focusout", startWebsiteSlider);
}

